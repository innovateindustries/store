function innovateLang() {
  try { return localStorage.getItem("innovate-lang") || "es"; }
  catch (e) { return "es"; }
}

function __t(key) {
  var l = innovateLang();
  if (I18N[l] && I18N[l][key] != null) return I18N[l][key];
  if (I18N.es[key] != null) return I18N.es[key];
  return null;
}

function applyLang(l) {
  if (!INNOVATE_LANGS[l]) l = "es";
  try { localStorage.setItem("innovate-lang", l); } catch (e) {}
  document.documentElement.setAttribute("lang", INNOVATE_LANGS[l].html);
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var v = __t(el.getAttribute("data-i18n"));
    if (v != null) el.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
    var v = __t(el.getAttribute("data-i18n-ph"));
    if (v != null) el.setAttribute("placeholder", v);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    var v = __t(el.getAttribute("data-i18n-aria"));
    if (v != null) el.setAttribute("aria-label", v);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
    var v = __t(el.getAttribute("data-i18n-alt"));
    if (v != null) el.setAttribute("alt", v);
  });
  document.querySelectorAll("[data-i18n-live]").forEach(function (el) {
    if (el.__liveOrig == null) el.__liveOrig = el.textContent;
    var map = LIVE_I18N[l];
    var v = map ? map[normLive(el.__liveOrig)] : null;
    el.textContent = (v != null) ? v : el.__liveOrig;
  });
  var f = document.getElementById("langFlag"), c = document.getElementById("langCode");
  if (f) { f.src = "https://flagcdn.com/w40/" + INNOVATE_LANGS[l].flag + ".png"; f.alt = INNOVATE_LANGS[l].code; }
  if (c) c.textContent = INNOVATE_LANGS[l].code;
  document.querySelectorAll("[data-setlang]").forEach(function (b) {
    b.classList.toggle("active-lang", b.getAttribute("data-setlang") === l);
  });
}

function closeLangMenu() {
  var m = document.getElementById("langMenu");
  if (m) m.classList.remove("show");
  var d = document.getElementById("langDrop");
  if (d) d.setAttribute("aria-expanded", "false");
}

document.addEventListener("DOMContentLoaded", function () {
  applyLang(innovateLang());
  document.querySelectorAll("[data-setlang]").forEach(function (b) {
    b.addEventListener("click", function () { applyLang(b.getAttribute("data-setlang")); closeLangMenu(); });
  });
  var drop = document.getElementById("langDrop");
  if (drop) drop.addEventListener("click", function (e) {
    if (e && e.stopPropagation) e.stopPropagation();
    var m = document.getElementById("langMenu");
    if (!m) return;
    var open = m.classList.toggle("show");
    drop.setAttribute("aria-expanded", open ? "true" : "false");
  });
  document.addEventListener("click", function () { closeLangMenu(); });
  document.addEventListener("keydown", function (e) { if (e && e.key === "Escape") closeLangMenu(); });
});

